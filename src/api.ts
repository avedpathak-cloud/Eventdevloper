export async function apiRequest<T = any>(path: string, options?: RequestInit): Promise<T> {
  const res = await fetch(path, {
    headers: {
      'Content-Type': 'application/json',
      ...(options?.headers || {}),
    },
    ...options,
  });
  const text = await res.text();
  let data: any = {};
  try {
    data = text ? JSON.parse(text) : {};
  } catch {
    data = {raw: text};
  }
  if (!res.ok) {
    throw new Error(data.error || `Request failed (${res.status})`);
  }
  return data as T;
}

export function formatINR(amount: number | string | undefined | null): string {
  const num = Number(amount || 0);
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(num);
}

export function modeLabel(mode: string): string {
  if (mode === 'event_and_catering') return 'Event + Catering';
  if (mode === 'event_only') return 'Event Only';
  if (mode === 'catering_only') return 'Catering Only';
  return mode;
}

export function statusColorClass(status: string): string {
  const s = (status || '').toLowerCase();
  if (
    s.includes('confirm') ||
    s === 'delivered' ||
    s === 'verified' ||
    s === 'completed' ||
    s === 'paid' ||
    s === 'available' ||
    s === 'approved' ||
    s === 'done'
  ) {
    return 'text-emerald-700';
  }
  if (
    s.includes('partial') ||
    s.includes('tentative') ||
    s.includes('pending') ||
    s === 'sent' ||
    s === 'dispatched' ||
    s === 'in_progress' ||
    s === 'prep_started' ||
    s === 'cooking' ||
    s === 'po_generated' ||
    s === 'need discussion'
  ) {
    return 'text-amber-700';
  }
  if (s.includes('cancel') || s.includes('not available') || s === 'overdue' || s === 'alert' || s === 'lost') {
    return 'text-red-700';
  }
  return 'text-slate-700';
}

export function downloadPrintableDocument(title: string, htmlBody: string) {
  const blob = new Blob(
    [
      `<!doctype html><html><head><meta charset="utf-8"><title>${title}</title>
      <style>
        body { font-family: system-ui, -apple-system, sans-serif; color: #0f172a; padding: 32px; max-width: 820px; margin: 0 auto; }
        h1 { font-size: 22px; margin: 0 0 6px; }
        .meta { color: #475569; font-size: 13px; margin-bottom: 20px; }
        table { width: 100%; border-collapse: collapse; margin: 16px 0; font-size: 13px; }
        th, td { border: 1px solid #cbd5e1; padding: 8px 10px; text-align: left; }
        th { background: #f1f5f9; font-weight: 600; }
        .num { text-align: right; font-variant-numeric: tabular-nums; }
        .footer { margin-top: 28px; font-size: 12px; color: #64748b; border-top: 1px solid #e2e8f0; padding-top: 12px; }
        @media print { .no-print { display: none; } }
      </style></head><body>
      <div class="no-print" style="margin-bottom:16px;"><button onclick="window.print()" style="padding:8px 14px;background:#4338ca;color:#fff;border:none;border-radius:6px;cursor:pointer;">Print / Save as PDF</button></div>
      ${htmlBody}
      <div class="footer">Generated by AuraEvents & CaterOps — Common Business Core</div>
      </body></html>`,
    ],
    {type: 'text/html;charset=utf-8'}
  );
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${title.toLowerCase().replace(/[^a-z0-9]+/g, '_')}.html`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
